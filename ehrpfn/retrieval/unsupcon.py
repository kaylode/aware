from typing import *
import torch
import torch.nn as nn
import torch.nn.functional as F
import numpy as np
import faiss
import os
import os.path as osp
from tqdm import tqdm
from ehrret.retrieval.base import Retriever
from ehrret.retrieval.utils import EarlyStopping
from sklearn.model_selection import train_test_split

class NTXentLoss(nn.Module):
    """
    Normalized Temperature-scaled Cross Entropy Loss (SimCLR loss).
    Treats each sample's two views as positives and others as negatives.
    """
    def __init__(self, temperature: float = 0.07):
        super().__init__()
        self.temperature = temperature

    def forward(self, z1: torch.Tensor, z2: torch.Tensor) -> torch.Tensor:
        """
        Args:
            z1: (B, D) normalized embeddings from first view
            z2: (B, D) normalized embeddings from second view
        """
        device = z1.device
        batch_size = z1.shape[0]
        
        # Concatenate views to get (2B, D)
        z = torch.cat([z1, z2], dim=0)
        
        # Compute similarity matrix (2B, 2B)
        sim_matrix = torch.matmul(z, z.T) / self.temperature
        
        # Mask out self-similarity (diagonal)
        mask = torch.eye(2 * batch_size, device=device).bool()
        sim_matrix = sim_matrix.masked_fill(mask, -1e9)
        
        # Target: i matches i + batch_size, and i + batch_size matches i
        pos_indices = torch.arange(batch_size, device=device)
        targets = torch.cat([pos_indices + batch_size, pos_indices], dim=0)
        
        loss = F.cross_entropy(sim_matrix, targets)
        return loss

class UnsupConEncoder(nn.Module):
    """
    Encoder for Unsupervised Contrastive Learning.
    Uses an attention-based feature selector and a projection head.
    """
    def __init__(self, n_features: int, hidden_dim: int = 512, embedding_dim: int = 128, dropout: float = 0.3):
        super().__init__()
        self.n_features = n_features
        self.embedding_dim = embedding_dim
        
        # Feature attention/weighting
        self.attention = nn.Sequential(
            nn.Linear(n_features, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, n_features),
            nn.Sigmoid()
        )

        # Projection head (essential for contrastive learning)
        self.projector = nn.Sequential(
            nn.Linear(n_features, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, embedding_dim)
        )
        
    def forward(self, x: torch.Tensor, return_projection: bool = False):
        """
        Args:
            x: (batch, n_features)
        Returns:
            weighted_x: (batch, n_features) - feature-weighted representation
            proj: (batch, embedding_dim) - normalized projection for contrastive loss
        """
        weights = self.attention(x)
        weighted_x = x * weights
        
        if return_projection:
            proj = F.normalize(self.projector(weighted_x), p=2, dim=1)
            return weighted_x, proj
        else:
            return weighted_x, None

class UnsupConRetriever(Retriever):
    """
    Unsupervised Contrastive Retriever.
    Trains embeddings without labels using SimCLR/SimCSE approach.
    Positives are generated by passing the same batch through the encoder twice (dropout as augmentation).
    """
    def __init__(
        self, 
        model: UnsupConEncoder, 
        field_to_use: str = 'raw_feature',
        distance: str = 'cosine', 
        k: int = 32, 
        temperature: float = 0.07,
        pretrained_path: str = None
    ):
        self.model = model
        self.distance = distance
        self.index = None
        self._is_fitted = False
        self.k = k
        self.field_to_use = field_to_use
        self.temperature = temperature
        self.pretrained_path = pretrained_path
        
        if pretrained_path is not None and osp.isfile(pretrained_path):
            self.load_state_dict(pretrained_path)

    def save_state_dict(self, path: str):
        if osp.dirname(path) != '':
            os.makedirs(osp.dirname(path), exist_ok=True)
        torch.save(self.model.state_dict(), path)
        print(f"Saved model weights to {path}")
        
    def load_state_dict(self, path: str):
        self.model.load_state_dict(torch.load(path))
        self.model.eval()
        self._is_fitted = True
        print(f"Loaded model weights from {path}")

    def fit(self, items: List[Dict], epochs: int = 100, lr: float = 1e-3, batch_size: int = 1024, patience: int = 10, **kwargs):
        """
        Train using Unsupervised Contrastive Loss (NT-Xent).
        No labels are used.
        """
        from torch.utils.data import DataLoader, TensorDataset
        import torch.optim as optim
        
        X_all = np.array([item[self.field_to_use] for item in items])
        
        # Split for validation (just to monitor loss)
        X_train, X_val = train_test_split(X_all, test_size=0.1, random_state=42)

        X_train_t = torch.FloatTensor(X_train)
        X_val_t = torch.FloatTensor(X_val)
        
        if not self._is_fitted:
            self.model.train()
            optimizer = optim.Adam(self.model.parameters(), lr=lr)
            criterion = NTXentLoss(temperature=self.temperature)
            
            train_loader = DataLoader(TensorDataset(X_train_t), batch_size=batch_size, shuffle=True, drop_last=True)
            val_loader = DataLoader(TensorDataset(X_val_t), batch_size=batch_size, shuffle=False, drop_last=False)

            early_stopping = EarlyStopping(patience=patience, mode='min')
            
            bar = tqdm(range(epochs), desc="Training UnsupCon Retriever")
            for epoch in bar:
                self.model.train()
                total_train_loss = 0
                num_batches = 0
                
                for (xb,) in train_loader:
                    optimizer.zero_grad()
                    
                    # SimCSE-style: Two views from the same batch with different dropout masks
                    _, z1 = self.model(xb, return_projection=True)
                    _, z2 = self.model(xb, return_projection=True)
                    
                    loss = criterion(z1, z2)
                    loss.backward()
                    optimizer.step()
                    
                    total_train_loss += loss.item()
                    num_batches += 1
                
                avg_train_loss = total_train_loss / num_batches

                # Validation
                self.model.eval()
                total_val_loss = 0
                num_val_batches = 0
                with torch.no_grad():
                    for (xb,) in val_loader:
                        # Even in eval, we might want to see the "potential" loss
                        # But typically we use dropout in training only.
                        # For validation monitoring, we can keep dropout on or just monitor consistency.
                        # Here we use dropout to generate views even for val loss monitoring.
                        self.model.train() 
                        _, zv1 = self.model(xb, return_projection=True)
                        _, zv2 = self.model(xb, return_projection=True)
                        v_loss = criterion(zv1, zv2)
                        total_val_loss += v_loss.item()
                        num_val_batches += 1
                
                avg_val_loss = total_val_loss / num_val_batches
                
                bar.set_postfix({
                    'train_loss': f'{avg_train_loss:.4f}',
                    'val_loss': f'{avg_val_loss:.4f}'
                })

                if early_stopping(avg_val_loss, self.model):
                    print(f"Early stopping at epoch {epoch}")
                    break
            
            early_stopping.restore_best_model(self.model)
            self._is_fitted = True
            if self.pretrained_path is not None:
                self.save_state_dict(self.pretrained_path)
        
        # Build FAISS index
        self.model.eval()
        with torch.no_grad():
            X_all_tensor = torch.FloatTensor(X_all)
            embeddings = []
            for i in range(0, X_all_tensor.size(0), 2048):
                batch = X_all_tensor[i:i+2048]
                weighted_x, _ = self.model(batch, return_projection=False)
                embeddings.append(weighted_x)
            embeddings = torch.cat(embeddings, dim=0).numpy()
            embeddings = np.ascontiguousarray(embeddings)
        
        if self.distance == 'cosine':
            faiss.normalize_L2(embeddings)
            self.index = faiss.IndexFlatIP(embeddings.shape[1])
        else:
            self.index = faiss.IndexFlatL2(embeddings.shape[1])
        
        self.index.add(embeddings)
        self.train_data = embeddings
        print(f"Built FAISS Index ({self.distance}) with {self.index.ntotal} vectors")
    
    def retrieve(self, query_items: List[Dict], k=None):
        if k is None:
            k = self.k
            
        X_query = np.array([item[self.field_to_use] for item in query_items])
        
        if not self._is_fitted:
            raise RuntimeError("Retriever is not fitted yet.")
        
        self.model.eval()
        with torch.no_grad():
            X_tensor = torch.FloatTensor(X_query)
            query_embeddings = []
            for i in range(0, X_tensor.size(0), 2048):
                batch = X_tensor[i:i+2048]
                weighted_x, _ = self.model(batch, return_projection=False)
                query_embeddings.append(weighted_x)
            query_embeddings = torch.cat(query_embeddings, dim=0).numpy()
            query_embeddings = np.ascontiguousarray(query_embeddings)
        
        if self.distance == 'cosine':
            faiss.normalize_L2(query_embeddings)
        
        distances, indices = self.index.search(query_embeddings, k)
        return indices

